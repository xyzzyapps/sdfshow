"""GPU parity check: generated field body vs an independent Python reference.

This is a manual test, not part of `pytest` (it needs a Vulkan GPU and a few
seconds). It renders the *actual generated GLSL* of `shows/ring` on a line of sample
points, decodes the distance from the pixels, and compares it with the analytic
torus written in Python.

Run from the repo root:

    .venv\\Scripts\\python.exe tests\\gpu_parity.py

Exit code 0 means the maximum absolute error is below the tolerance.
"""

from __future__ import annotations

import math
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from sdfshow import config as C  # noqa: E402
from sdfshow.fields import load  # noqa: E402
from sdfshow.show import parse  # noqa: E402

N = 256
WIDTH, HEIGHT = N, 1
LO, HI = -2.0, 2.0
ENC_MIN, ENC_MAX = -1.0, 3.0  # distance range encoded as 0..1
TOLERANCE = 0.01


def _rot_x(p: tuple[float, float, float], a: float):
    c, s = math.cos(a), math.sin(a)
    return (p[0], c * p[1] - s * p[2], s * p[1] + c * p[2])


def _rot_y(p: tuple[float, float, float], a: float):
    c, s = math.cos(a), math.sin(a)
    return (c * p[0] + s * p[2], p[1], -s * p[0] + c * p[2])


def reference(p: tuple[float, float, float]) -> float:
    """The torus from shows/ring, written independently of the template."""
    q = _rot_x(_rot_y(p, 0.0), 0.7)
    return math.hypot(math.hypot(q[0], q[2]) - 1.2, q[1]) - 0.08


def _shader() -> str:
    """Wrap the field's generated body in a one-row distance evaluator."""
    show = parse("ring", C.SHOWS / "ring" / "show.md")
    field = load(show.fields_md, show.clock).fields[0]
    return f"""\
//!HOOK MAIN
//!BIND HOOKED
//!DESC parity

vec3 rotX(vec3 p, float a) {{
    float c = cos(a), s = sin(a);
    return vec3(p.x, c * p.y - s * p.z, s * p.y + c * p.z);
}}
vec3 rotY(vec3 p, float a) {{
    float c = cos(a), s = sin(a);
    return vec3(c * p.x + s * p.z, p.y, -s * p.x + c * p.z);
}}

float field(vec3 p, float t) {{
    {field.body}
}}

vec4 hook() {{
    float x = {LO:.6g} + HOOKED_pos.x * {HI - LO:.6g};
    float d = field(vec3(x, 0.3, 0.2), 0.0);
    float v = clamp((d - ({ENC_MIN:.6g})) / ({ENC_MAX - ENC_MIN:.6g}), 0.0, 1.0);
    return vec4(v, v, v, 1.0);
}}
"""


def _script(shader_path: Path) -> str:
    """A VapourSynth script that renders the evaluator and returns 16-bit RGB."""
    return f'''"""Generated by tests/gpu_parity.py."""
import vapoursynth as vs

core = vs.core
with open(r"{shader_path.as_posix()}", encoding="utf-8") as fh:
    shader = fh.read()
clip = core.std.BlankClip(
    width={WIDTH}, height={HEIGHT}, format=vs.YUV444P16, length=1, fpsnum=30
)
clip = core.placebo.Shader(
    clip, shader_s=shader, width={WIDTH}, height={HEIGHT},
    sigmoidize=False, linearize=False, matrix=5,
)
clip.set_output()
'''


def main() -> int:
    """Render the evaluator, decode the distances and compare."""
    out = C.OUTPUT / "parity"
    out.mkdir(parents=True, exist_ok=True)
    shader_path = out / "parity.glsl"
    script_path = out / "parity.vpy"
    shader_path.write_text(_shader(), encoding="utf-8")
    script_path.write_text(_script(shader_path), encoding="utf-8")

    vsp = subprocess.run(
        [str(C.VSPIPE), "-c", "y4m", str(script_path), "-"],
        capture_output=True,
        check=False,
    )
    if vsp.returncode != 0:
        print(vsp.stderr.decode("utf-8", "replace"))
        return 1
    dec = subprocess.run(
        [
            "ffmpeg",
            "-hide_banner",
            "-v",
            "error",
            "-f",
            "yuv4mpegpipe",
            "-i",
            "-",
            "-f",
            "rawvideo",
            "-pix_fmt",
            "rgb48le",
            "-",
        ],
        input=vsp.stdout,
        capture_output=True,
        check=False,
    )
    if dec.returncode != 0:
        print(dec.stderr.decode("utf-8", "replace"))
        return 1
    pixels = dec.stdout
    if len(pixels) < WIDTH * HEIGHT * 6:
        print(f"short read: {len(pixels)} bytes")
        return 1

    worst = 0.0
    worst_x = LO
    for i in range(N):
        x = LO + (i + 0.5) / N * (HI - LO)
        value = (pixels[i * 6] | (pixels[i * 6 + 1] << 8)) / 65535.0
        got = ENC_MIN + value * (ENC_MAX - ENC_MIN)
        want = reference((x, 0.3, 0.2))
        error = abs(got - want)
        if error > worst:
            worst = error
            worst_x = x

    print(f"samples: {N}  max abs error: {worst:.5f} at x={worst_x:.3f}")
    if worst > TOLERANCE:
        print(f"FAIL: tolerance is {TOLERANCE}")
        return 1
    print("OK: generated field matches the reference")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

"""Render one bubble's ink function on its own.

Separates "the font is wrong" from "the bubble's frame is wrong". Writes
``output/fontprobe/bubble_ink.png``.

    .venv\\Scripts\\python.exe tools/bubble_probe.py
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from sdfshow import config as C  # noqa: E402
from sdfshow.dialog import character  # noqa: E402
from sdfshow.fields import load  # noqa: E402
from sdfshow.glyphs import emit_glyph_function  # noqa: E402
from sdfshow.show import parse  # noqa: E402


def main() -> int:
    """Render the first AINA line as solid ink over a big grid of cells."""
    show = parse("diner", C.SHOWS / "diner" / "show.md")
    load(
        show.fields_md,
        show.clock,
        show.show_md.read_text(encoding="utf-8"),
        gen_dir=show.gen,
    )
    line = character(show.dialogue, "AINA")[0]
    text = line.text.upper()
    count = len(text)
    codes = ", ".join(str(ord(c)) for c in text)
    font = emit_glyph_function(set(text))

    out = C.OUTPUT / "fontprobe"
    out.mkdir(parents=True, exist_ok=True)
    shader = out / "bubble_ink.glsl"
    shader.write_text(
        f"""\
//!HOOK MAIN
//!BIND HOOKED
//!DESC bubble ink probe

#define FPS 30.0
#define TIME0 0.0

{font}
const int N = {count};
const int CODES[N] = int[N]({codes});

vec4 hook() {{
    // Cell space across the whole frame: x = 0..N columns, y = -0.5..1.5 rows.
    float x = HOOKED_pos.x * float(N);
    float y = 1.5 - HOOKED_pos.y * 2.0;
    int idx = int(floor(x));
    int g = 0;
    if (idx >= 0 && idx < N) g = CODES[idx];
    vec2 cell = vec2(x - float(idx), y - 0.25);
    float d = glyph_dist(g, cell) - 0.06;
    float v = d < 0.0 ? 0.02 : 0.9;
    return vec4(v, v, v, 1.0);
}}
""",
        encoding="utf-8",
    )
    width, height = 1200, 300
    script = out / "bubble_ink.vpy"
    script.write_text(
        f'''"""Generated by tools/bubble_probe.py."""
import vapoursynth as vs

core = vs.core
with open(r"{shader.as_posix()}", encoding="utf-8") as fh:
    shader = fh.read()
clip = core.std.BlankClip(
    width={width}, height={height}, format=vs.YUV444P16, length=1, fpsnum=30
)
clip = core.placebo.Shader(
    clip, shader_s=shader, width={width}, height={height},
    sigmoidize=False, linearize=False, matrix=5,
)
clip.set_output()
''',
        encoding="utf-8",
    )
    png = out / "bubble_ink.png"
    vsp = subprocess.run(
        [str(C.VSPIPE), "-c", "y4m", str(script), "-"],
        capture_output=True,
        check=False,
    )
    if vsp.returncode != 0:
        print(vsp.stderr.decode("utf-8", "replace")[-2000:])
        return 1
    enc = subprocess.run(
        [
            "ffmpeg",
            "-hide_banner",
            "-y",
            "-v",
            "error",
            "-f",
            "yuv4mpegpipe",
            "-i",
            "-",
            "-frames:v",
            "1",
            "-update",
            "1",
            str(png),
        ],
        input=vsp.stdout,
        capture_output=True,
        check=False,
    )
    if enc.returncode != 0:
        print(enc.stderr.decode("utf-8", "replace")[-2000:])
        return 1
    print(f"{png}  ({text!r})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

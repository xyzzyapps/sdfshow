"""Render the stroke font on its own, so glyph bugs are separable from scene bugs.

Not part of the test suite: it needs a GPU. Run it after changing `glyphs.py`:

    .venv\\Scripts\\python.exe tools/font_probe.py

It writes ``output/fontprobe/probe.png``: the string below, drawn as capsules.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from sdfshow import config as C  # noqa: E402
from sdfshow.glyphs import emit_glyph_function  # noqa: E402

TEXT = "SO WHO IS SHE ANYWAY?"
SCALE = 100  # pixels per cell


def main() -> int:
    """Build the probe shader, render one frame, and report where it was written."""
    out = C.OUTPUT / "fontprobe"
    out.mkdir(parents=True, exist_ok=True)
    codes = ", ".join(str(ord(c)) for c in TEXT)
    count = len(TEXT)
    font = emit_glyph_function(set(TEXT))
    scene = f"""\
//!HOOK MAIN
//!BIND HOOKED
//!DESC font probe

#define FPS 30.0
#define TIME0 0.0

{font}
const int CODES[{count}] = int[{count}]({codes});

vec4 hook() {{
    vec2 res = target_size;
    int idx = int(floor(HOOKED_pos.x * float({count})));
    int g = 0;
    if (idx >= 0 && idx < {count}) g = CODES[idx];
    vec2 q = vec2(HOOKED_pos.x * float({count}) - float(idx), HOOKED_pos.y);
    float d = glyph_dist(g, q) - 0.06;
    float v = d < 0.0 ? 0.03 : 0.95;
    return vec4(v, v, v, 1.0);
}}
"""
    shader = out / "probe.glsl"
    shader.write_text(scene, encoding="utf-8")
    width, height = SCALE * count, SCALE * 2
    script = out / "probe.vpy"
    script.write_text(
        f'''"""Generated by tools/font_probe.py."""
import vapoursynth as vs

core = vs.core
with open(r"{shader.as_posix()}", encoding="utf-8") as fh:
    shader = fh.read()
clip = core.std.BlankClip(
    width={width}, height={height}, format=vs.YUV444P16, length=1, fpsnum=30
)
clip = core.placebo.Shader(
    clip, shader_s=shader, width={width}, height={height},
    sigmoidize=False, linearize=False, matrix=5,
)
clip.set_output()
''',
        encoding="utf-8",
    )
    png = out / "probe.png"
    encode = subprocess.run(
        [
            "ffmpeg",
            "-hide_banner",
            "-y",
            "-v",
            "error",
            "-f",
            "yuv4mpegpipe",
            "-i",
            "-",
            "-frames:v",
            "1",
            "-update",
            "1",
            str(png),
        ],
        input=subprocess.run(
            [str(C.VSPIPE), "-c", "y4m", str(script), "-"],
            capture_output=True,
            check=False,
        ).stdout,
        capture_output=True,
        check=False,
    )
    if encode.returncode != 0:
        print(encode.stderr.decode("utf-8", "replace"))
        return 1
    print(png)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
